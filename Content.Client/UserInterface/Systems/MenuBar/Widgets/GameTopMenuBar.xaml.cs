using Robust.Client.AutoGenerated;
using Content.Shared.CCVar;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client.UserInterface.Systems.MenuBar.Widgets
{
    [GenerateTypedNameReferences]
    public sealed partial class GameTopMenuBar : UIWidget
    {
        private readonly IConfigurationManager _cfg = IoCManager.Resolve<IConfigurationManager>();
        private readonly IUriOpener _uriOpener = IoCManager.Resolve<IUriOpener>();
        private Uri? _boostyUri;

        public GameTopMenuBar()
        {
            RobustXamlLoader.Load(this);
            BoostyButton.OnPressed += _ =>
            {
                if (_boostyUri != null)
                    _uriOpener.OpenUri(_boostyUri.AbsoluteUri);
            };
        }

        protected override void EnteredTree()
        {
            base.EnteredTree();
            _cfg.OnValueChanged(CCVars.InfoLinksBoosty, UpdateBoostyLink, invokeImmediately: true);
        }

        protected override void ExitedTree()
        {
            _cfg.UnsubValueChanged(CCVars.InfoLinksBoosty, UpdateBoostyLink);
            base.ExitedTree();
        }

        private void UpdateBoostyLink(string url)
        {
            _boostyUri = Uri.TryCreate(url, UriKind.Absolute, out var uri) &&
                uri.Scheme == Uri.UriSchemeHttps && uri.Host.Equals("boosty.to", StringComparison.OrdinalIgnoreCase)
                ? uri
                : null;
            BoostyButton.Visible = _boostyUri != null;
        }
    }
}
