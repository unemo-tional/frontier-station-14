[GenerateTypedNameReferences]
public sealed partial class ShipyardConsoleMenu : FancyWindow
{
    /// <summary>
    ///     How the vessels are sorted in the shipyard menu
    /// </summary>
    private enum VesselSortBy : byte
    {
        Name,
        Price
    }

    [Dependency] private IPrototypeManager _protoManager = default!;

    public record OrderApprovedEventArgs(ProtoId<VesselPrototype> Vessel, ProtoId<ShuttleAtmospherePrototype>? Atmosphere);

    public event Action<ButtonEventArgs>? OnSellShip;
    public event Action<OrderApprovedEventArgs>? OnOrderApproved;
    private readonly List<VesselSize> _categoryStrings = new();
    private readonly List<VesselClass> _classStrings = new();
    private readonly List<VesselEngine> _engineStrings = new();
    private readonly List<VesselSortBy> _sortByStrings = new();
    private VesselSize? _category;
    private VesselClass? _class;
    private VesselEngine? _engine;
    private VesselSortBy? _sortby;

    private List<string> _lastAvailableProtos = new();
    private List<string> _lastUnavailableProtos = new();
    private bool _freeListings = false;
    private bool _validId = false;
    [Dependency] private IEntitySystemManager _entitySystems = default!;
    private VesselPrototype? _selectedVessel;
    private readonly Dictionary<string, (VesselPrototype Vessel, string Price, bool CanPurchase, Button Button)> _listings = new();

    public ShipyardConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("shipyard-console-menu-title");
        SearchBar.OnTextChanged += OnSearchBarTextChanged;
        Categories.OnItemSelected += OnCategoryItemSelected;
        Classes.OnItemSelected += OnClassItemSelected;
        Engines.OnItemSelected += OnEngineItemSelected;
        Atmosphere.OnItemSelected += OnAtmosphereItemSelected;
        SortBy.OnItemSelected += OnSortByItemSelected;
        PreviewView.StateChanged += RefreshPreview;
        PreviewFitButton.OnPressed += _ => PreviewView.FitWhole();
        PreviewZoomInButton.OnPressed += _ => PreviewView.ZoomIn();
        PreviewZoomOutButton.OnPressed += _ => PreviewView.ZoomOut();
        PurchaseButton.OnPressed += _ => PurchaseSelectedVessel();
        GuidebookButton.OnPressed += _ =>
        {
            if (_selectedVessel?.GuidebookPage is { } page)
                _entitySystems.GetEntitySystem<GuidebookSystem>().OpenHelp(new List<ProtoId<Content.Shared.Guidebook.GuideEntryPrototype>> { page });
        };
        RefreshPreview();
        SellShipButton.OnPressed += (args) => { OnSellShip?.Invoke(args); };
    }


    private void OnCategoryItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetCategoryText(args.Id);
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private void OnClassItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetClassText(args.Id);
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private void OnEngineItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetEngineText(args.Id);
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private void OnAtmosphereItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        Atmosphere.SelectId(args.Id);
    }

    private void OnSortByItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetSortByText(args.Id);
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private void OnSearchBarTextChanged(LineEdit.LineEditEventArgs args)
    {
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private void SetCategoryText(int id)
    {
        _category = id == 0 ? null : _categoryStrings[id];
        Categories.SelectId(id);
    }
    private void SetClassText(int id)
    {
        _class = id == 0 ? null : _classStrings[id];
        Classes.SelectId(id);
    }
    private void SetEngineText(int id)
    {
        _engine = id == 0 ? null : _engineStrings[id];
        Engines.SelectId(id);
    }

    private void SetSortByText(int id)
    {
        _sortby = id == 0 ? null : _sortByStrings[id];
        SortBy.SelectId(id);
    }
    /// <summary>
    ///     Populates the list of products that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateProducts(List<string> availablePrototypes, List<string> unavailablePrototypes, bool free, bool canPurchase)
    {
        Vessels.RemoveAllChildren();
        _listings.Clear();

        var search = SearchBar.Text.Trim().ToLowerInvariant();

        var newVessels = GetVesselPrototypesFromIds(availablePrototypes);
        AddVesselsToControls(newVessels, search, free, canPurchase);

        var newUnavailableVessels = GetVesselPrototypesFromIds(unavailablePrototypes);
        AddVesselsToControls(newUnavailableVessels, search, free, false);

        CatalogTitle.Text = Loc.GetString("shipyard-preview-catalog", ("count", _listings.Count));
        if (_selectedVessel != null && _listings.TryGetValue(_selectedVessel.ID, out var selected))
            SelectVessel(selected.Vessel, selected.Price, selected.CanPurchase);
        else if (_listings.Count > 0)
        {
            var first = _listings.Values.First();
            SelectVessel(first.Vessel, first.Price, first.CanPurchase);
        }
        else
            SelectVessel(null);

        _lastAvailableProtos = availablePrototypes;
        _lastUnavailableProtos = unavailablePrototypes;
    }

    /// <summary>
    /// Given a set of prototype IDs, returns a corresponding set of prototypes, ordered by name.
    /// </summary>
    private List<VesselPrototype?> GetVesselPrototypesFromIds(IEnumerable<string> protoIds)
    {
        var vesselList = protoIds.Select(it => _protoManager.TryIndex<VesselPrototype>(it, out var proto) ? proto : null)
            .Where(it => it != null)
            .ToList();

        var sortOrder = _sortby != null ? _sortby! : VesselSortBy.Name;

        switch (sortOrder)
        {
            case VesselSortBy.Name:
                vesselList.Sort((x, y) =>
                    string.Compare(x!.Name, y!.Name, StringComparison.CurrentCultureIgnoreCase));
                break;

            case VesselSortBy.Price:
                vesselList.Sort((x, y) => x!.Price.CompareTo(y!.Price));
                break;
        }
        return vesselList;
    }

    /// <summary>
    /// Adds the matching vessels to the catalog.
    /// </summary>
    private void AddVesselsToControls(IEnumerable<VesselPrototype?> vessels, string search, bool free, bool canPurchase)
    {
        foreach (var prototype in vessels)
        {
            // Filter any ships
            if (_category != null && !prototype!.Category.Equals(_category))
                continue;
            if (_class != null && !prototype!.Classes.Contains(_class.Value))
                continue;
            if (_engine != null && !prototype!.Engines.Contains(_engine.Value))
                continue;
            if (search.Length > 0 && !prototype!.Name.ToLowerInvariant().Contains(search))
                continue;

            string priceText;
            if (free)
                priceText = Loc.GetString("shipyard-console-menu-listing-free");
            else
                priceText = BankSystemExtensions.ToSpesoString(prototype!.Price);

            var vessel = prototype!;
            if (_listings.ContainsKey(vessel.ID))
                continue;

            var entry = new Button
            {
                Text = $"{vessel.Name}   ·   {priceText}",
                ToolTip = vessel.Description,
                ClipText = true,
                HorizontalExpand = true,
                ToggleMode = true,
            };
            _listings.Add(vessel.ID, (vessel, priceText, canPurchase, entry));
            entry.OnPressed += _ => SelectVessel(vessel, priceText, canPurchase);
            Vessels.AddChild(entry);
        }
    }

    private void SelectVessel(VesselPrototype? vessel, string price = "", bool canPurchase = false)
    {
        if (_selectedVessel?.ID != vessel?.ID || PurchaseButton.Disabled != !canPurchase)
            PurchaseButton.ClearIsConfirming();

        if (_selectedVessel != null && _listings.TryGetValue(_selectedVessel.ID, out var previous))
            previous.Button.Pressed = false;

        _selectedVessel = vessel;
        if (vessel != null && _listings.TryGetValue(vessel.ID, out var selected))
            selected.Button.Pressed = true;
        PurchaseButton.Disabled = !canPurchase;
        SelectedPriceLabel.Text = price;
        GuidebookButton.Visible = vessel?.GuidebookPage != null;
        InfoName.Text = vessel?.Name ?? string.Empty;
        InfoSize.Text = vessel == null ? string.Empty : Loc.GetString($"shipyard-console-category-{vessel.Category}");
        InfoClasses.Text = vessel == null ? string.Empty : string.Join(", ", vessel.Classes.Select(value => Loc.GetString($"shipyard-console-class-{value}")));
        InfoEngines.Text = vessel == null ? string.Empty : string.Join(", ", vessel.Engines.Select(value => Loc.GetString($"shipyard-console-engine-{value}")));
        InfoDescription.SetMessage(vessel?.Description ?? string.Empty);
        PreviewView.SetVessel(vessel);
        RefreshPreview();
    }

    private void RefreshPreview()
    {
        PreviewTitle.Text = _selectedVessel?.Name ?? string.Empty;
        PreviewSubtitle.Text = InfoSize.Text;
        PreviewStatus.Text = _selectedVessel == null
            ? Loc.GetString("shipyard-preview-select")
            : PreviewView.Entry is { } entry
                ? entry.Failed ? Loc.GetString("shipyard-preview-failed") : string.Empty
                : Loc.GetString("shipyard-preview-loading");
        InfoLayout.Text = PreviewView.Entry?.Info is { } info
            ? Loc.GetString("shipyard-preview-dimensions", ("width", info.Dimensions.X), ("height", info.Dimensions.Y))
            : string.Empty;
    }

    private void PurchaseSelectedVessel()
    {
        if (_selectedVessel == null || PurchaseButton.Disabled)
            return;

        var atmosphere = Atmosphere.SelectedMetadata is AtmosButtonMetadata metadata ? metadata.Proto : null;
        Atmosphere.Select(0);
        OnOrderApproved?.Invoke(new OrderApprovedEventArgs(_selectedVessel.ID, atmosphere?.ID));
    }


    /// <summary>
    ///     Populates the list categories that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateCategories(List<string> availablePrototypes, List<string> unavailablePrototypes)
    {
        _categoryStrings.Clear();
        Categories.Clear();

        AddCategoriesFromPrototypes(availablePrototypes);
        AddCategoriesFromPrototypes(unavailablePrototypes);

        _categoryStrings.Sort();

        // Add "All" category at the top of the list
        _categoryStrings.Insert(0, VesselSize.All);

        foreach (var str in _categoryStrings)
        {
            Categories.AddItem(Loc.GetString($"shipyard-console-category-{str}"));
        }
    }

    /// <summary>
    /// Adds all ship categories from a list of vessel prototypes to the current control's list if they are missing.
    /// </summary>
    private void AddCategoriesFromPrototypes(IEnumerable<string> prototypes)
    {
        foreach (var protoId in prototypes)
        {
            if (!_protoManager.TryIndex<VesselPrototype>(protoId, out var prototype))
                continue;

            if (!_categoryStrings.Contains(prototype.Category) && prototype.Category != VesselSize.All)
            {
                _categoryStrings.Add(prototype.Category);
            }
        }
    }

    /// <summary>
    ///     Populates the list classes that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateClasses(List<string> availablePrototypes, List<string> unavailablePrototypes)
    {
        _classStrings.Clear();
        Classes.Clear();

        AddClassesFromPrototypes(availablePrototypes);
        AddClassesFromPrototypes(unavailablePrototypes);

        _classStrings.Sort();

        // Add "All" category at the top of the list
        _classStrings.Insert(0, VesselClass.All);

        foreach (var str in _classStrings)
        {
            Classes.AddItem(Loc.GetString($"shipyard-console-class-{str}"));
        }
    }

    /// <summary>
    /// Adds all ship classes from a list of vessel prototypes to the current control's list if they are missing.
    /// </summary>
    private void AddClassesFromPrototypes(IEnumerable<string> prototypes)
    {
        foreach (var protoId in prototypes)
        {
            if (!_protoManager.TryIndex<VesselPrototype>(protoId, out var prototype))
                continue;

            foreach (var cl in prototype.Classes)
            {
                if (!_classStrings.Contains(cl) && cl != VesselClass.All)
                {
                    _classStrings.Add(cl);
                }
            }
        }
    }

    /// <summary>
    ///     Populates the list engines that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateEngines(List<string> availablePrototypes, List<string> unavailablePrototypes)
    {
        _engineStrings.Clear();
        Engines.Clear();

        AddEnginesFromPrototypes(availablePrototypes);
        AddEnginesFromPrototypes(unavailablePrototypes);

        _engineStrings.Sort();

        // Add "All" category at the top of the list
        _engineStrings.Insert(0, VesselEngine.All);

        foreach (var str in _engineStrings)
        {
            Engines.AddItem(Loc.GetString($"shipyard-console-engine-{str}"));
        }
    }

    /// <summary>
    /// Adds all ship engine power type from a list of vessel prototypes to the current control's list if they are missing.
    /// </summary>
    private void AddEnginesFromPrototypes(IEnumerable<string> prototypes)
    {
        foreach (var protoId in prototypes)
        {
            if (!_protoManager.TryIndex<VesselPrototype>(protoId, out var prototype))
                continue;

            foreach (var cl in prototype.Engines)
            {
                if (!_engineStrings.Contains(cl) && cl != VesselEngine.All)
                {
                    _engineStrings.Add(cl);
                }
            }
        }
    }

    /// <summary>
    /// Adds available shuttle atmospheres to the selection box, or hides the box if no custom atmospheres are available.
    /// </summary>
    public void PopulateAtmos(List<ProtoId<ShuttleAtmospherePrototype>>? atmospheres)
    {
        CustomAtmosContainer.Visible = atmospheres != null;
        Atmosphere.Clear();
        if (atmospheres == null)
            return;

        Atmosphere.AddItem(Loc.GetString("shipyard-console-menu-atmos-default"));
        var i = 1;
        foreach (var protoId in atmospheres)
        {
            if (!_protoManager.Resolve(protoId, out var atmosphere))
                continue;
            Atmosphere.AddItem(atmosphere.Name, i);
            Atmosphere.SetItemMetadata(i, new AtmosButtonMetadata(atmosphere));
            ++i;
        }
    }

    /// <summary>
    ///     Populates the sort-by types in the Sort By button
    /// </summary>
    public void PopulateSortByTypes()
    {
        SortBy.Clear();

        _sortByStrings.Clear();
        foreach (var sort in Enum.GetValues<VesselSortBy>())
        {
            _sortByStrings.Add(sort);
        }

        foreach (var str in _sortByStrings)
        {
            SortBy.AddItem(Loc.GetString($"shipyard-console-sortby-{str}"));
        }
    }

    public void UpdateState(ShipyardConsoleInterfaceState state)
    {
        BalanceLabel.Text = BankSystemExtensions.ToSpesoString(state.Balance);
        var shipPrice = 0;
        if (!state.FreeListings)
            shipPrice = state.ShipSellValue;

        ShipAppraisalLabel.Text = $"{BankSystemExtensions.ToSpesoString(shipPrice)} ({state.SellRate * 100.0f:F1}%)";
        SellShipButton.Disabled = state.ShipDeedTitle == null;
        TargetIdButton.Text = state.IsTargetIdPresent
            ? Loc.GetString("id-card-console-window-eject-button")
            : Loc.GetString("id-card-console-window-insert-button");
        NoDeedHelperContainer.Visible = !state.IsTargetIdPresent;
        DeedContainer.Visible = state.IsTargetIdPresent;
        if (state.ShipDeedTitle != null)
        {
            DeedTitle.Text = state.ShipDeedTitle;
        }
        else
        {
            DeedTitle.Text = $"None";
        }
        _freeListings = state.FreeListings;
        _validId = state.IsTargetIdPresent;
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);
    }

    private record AtmosButtonMetadata(ShuttleAtmospherePrototype Proto);
}
